--[[--------------------------------------------------------------------
    grm_parcel — посылка курьера.

    ЗАЧЕМ. Работа «Курьер» обещала «доставьте посылку», но возить было
    нечего: задача сводилась к «дойди до координаты». Посылку нельзя было
    ни потерять, ни украсть, поэтому у доставки не было ни одного
    пересечения с другими игроками.

    Теперь это ФИЗИЧЕСКИЙ предмет. Его несут в руках, он выпадает при
    смерти, его может подобрать и донести кто угодно — включая того, кто
    отнял её у курьера.

    Состояния:
      Carrier   — кто несёт (NULL, если лежит в мире)
      OwnerKey  — персонаж, которому выдан заказ (для сверки при сдаче)
      Fragile   — хрупкая: разбивается от сильного удара
----------------------------------------------------------------------]]
ENT.Type = "anim"
ENT.Base = "base_gmodentity"
ENT.PrintName = "Посылка"
ENT.Category = "GRM — Работы"
ENT.Spawnable = false

function ENT:SetupDataTables()
    self:NetworkVar("Entity", 0, "Carrier")
    self:NetworkVar("String", 0, "OwnerKey")
    self:NetworkVar("String", 1, "Label")
    self:NetworkVar("Bool", 0, "Fragile")
end
