--[[--------------------------------------------------------------------
    grm_quest_checkpoint — маркер-чекпоинт квеста.

    ЗАКАЗ ВЛАДЕЛЬЦА (30.08): «нужен модуль для графа, отвечающий за
    размещение маркеров, чекпоинтов, который можно будет связать с
    выплатами/ачивками. Проп круга из plastic, материал debugwhite,
    красный, прозрачность 50%, как в логистике. Чекпоинты крутящиеся.»

    ЧТО ЭТО. Точка на карте, до которой игрок должен дойти. Ставится
    блоком ЧЕКПОИНТ в узловом редакторе квестов и соединяется линией с
    чем угодно: наградой, ачивкой, кат-сценой, следующим этапом.

    ВИД взят с точки погрузки логистики, чтобы маркеры сервера
    выглядели одинаково: круглая пластина, материал debugwhite, красный
    цвет, альфа 127 (это и есть «прозрачность 50%»).

    Поля:
      QuestID     — какому квесту принадлежит
      CheckpointID— идентификатор точки внутри квеста (для связей графа)
      Label       — подпись над маркером
      Radius      — радиус срабатывания

    ПОЧЕМУ ЗДЕСЬ НЕТ ФЛАГА «ПРОЙДЕНО». Сетевая переменная одна на всех
    игроков, а прогресс личный. Флаг Reached существовал и приводил к
    вранью: первый прошедший ставил его, и маркер прятался у ВСЕХ, кто
    точку ещё не проходил. Правда о пройденности живёт только в прогрессе
    игрока (p.checkpoints), клиент её оттуда и читает.
----------------------------------------------------------------------]]
ENT.Type = "anim"
ENT.Base = "base_gmodentity"
ENT.PrintName = "Чекпоинт квеста"
ENT.Category = "GRM — Квесты"
ENT.Spawnable = false
ENT.AdminOnly = true

--[[ МОДЕЛЬ. Ровно та же круглая труба, что у точки погрузки логистики
     (LoadingPointModel в sh_grm_logistics_config): владелец указал
     логистику эталоном, а эта модель уже проверена на живом сервере —
     докачивать клиенту нечего.

     Запасные варианты на случай, если основная почему-то не найдётся:
     маркер без модели превратился бы в невидимый «ошибочный» кубик, и
     точку квеста стало бы не найти. ]]
ENT.CheckpointModel = "models/hunter/tubes/tube2x2x1.mdl"
ENT.CheckpointModelFallbacks = {
    "models/hunter/tubes/tube2x2x1.mdl",
    "models/hunter/plates/plate1x1.mdl",
    "models/props_junk/wood_crate001a.mdl",
}

-- Скорость вращения, градусов в секунду. Медленно: маркер должен
-- привлекать внимание, а не мельтешить в кадре кат-сцены.
ENT.SpinSpeed = 45

function ENT:SetupDataTables()
    self:NetworkVar("String", 0, "QuestID")
    self:NetworkVar("String", 1, "CheckpointID")
    self:NetworkVar("String", 2, "Label")
    self:NetworkVar("Float", 0, "Radius")
end
