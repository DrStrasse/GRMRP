    grm_home_bed — домашняя кровать (жильё).

    ЗАКАЗ ВЛАДЕЛЬЦА (28.08): «для жилья нужна энтити домашней кровати,
    которая будет точкой сохранения/входа/выхода».

    ЧТО ЭТО ДАЁТ.
      • ТОЧКА ВХОДА. Появляясь дома, игрок встаёт у своей кровати, а не
        там, куда попадёт эвристика «от двери внутрь комнаты». Раньше в
        сложной планировке (второй этаж, длинный коридор) она промахивалась,
        и приходилось задавать точку админской командой.
      • ТОЧКА ВЫХОДА. Лёг спать — вышел из игры. Вернулся — там же.
      • ТОЧКА СОХРАНЕНИЯ. Место запоминается сразу, а не ждёт автоснимка,
        который делается раз в полминуты.

    Владельца кровать сама не хранит: она принадлежит квартире, в чьей
    зоне стоит — ровно как домашний шкаф. Продали жильё, и кровать
    перешла новому хозяину, без отдельной перепривязки.
