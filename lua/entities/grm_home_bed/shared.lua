function ENT:SetupDataTables()
    --[[ Кто сейчас лежит. Нужно и клиенту (подпись, вид от третьего
         лица), и серверу — поэтому сетевое поле, а не обычная переменная. ]]
    self:NetworkVar("Entity", 0, "Sleeper")
    --[[ Привязана ли кровать к жилью. Ставится сервером; по нему
         подпись сразу говорит, работает кровать или её поставили мимо
         квартиры. ]]
    self:NetworkVar("Bool", 0, "Linked")
    self:NetworkVar("String", 0, "HomeName")
end
